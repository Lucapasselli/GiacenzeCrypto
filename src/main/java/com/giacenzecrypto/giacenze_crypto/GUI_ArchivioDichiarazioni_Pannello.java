    /** Mette o toglie il segno di definitiva, con le conferme di {@link Principale_Dichiarazioni}. */
    private void CambiaDefinitiva(Dichiarazioni.Dichiarazione d) {
        if (d == null) {
            return;
        }
        boolean cambiata = d.Definitiva
                ? Principale_Dichiarazioni.TogliDefinitiva(d, Proprietario())
                : Principale_Dichiarazioni.SegnaDefinitiva(d, Proprietario());
        if (cambiata) {
            RicaricaMantenendoSelezione(d);
        }
    }

    /** Rilegge l'archivio e ricostruisce le due tabelle. */
    public final void Ricarica() {
        Component c = Proprietario() != null ? Proprietario() : this;
        c.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            Elenco = Dichiarazioni.Elenco();
            ModelloElenco().setRowCount(0);
            for (Object[] r : Principale_Dichiarazioni.RigheElenco(Elenco)) {
                ModelloElenco().addRow(r);
            }
            Label_Riepilogo.setText(TestoRiepilogo());
            AdattaLarghezzaColonne(Tabella_Elenco);
        } finally {
            c.setCursor(Cursor.getDefaultCursor());
        }
        MostraDettaglio();
        AggiornaStatoPulsanti();
    }

    private void RicaricaMantenendoSelezione(Dichiarazioni.Dichiarazione d) {
        String id = d == null ? "" : d.Id();
        Ricarica();
        for (int i = 0; i < Elenco.size(); i++) {
            if (Elenco.get(i).Id().equals(id)) {
                int vista = Tabella_Elenco.convertRowIndexToView(i);
                if (vista >= 0) {
                    Tabella_Elenco.setRowSelectionInterval(vista, vista);
                }
                return;
            }
        }
    }

    /** Corta di proposito: sta nella stessa riga dei pulsanti (vedi {@code GUI_Backup_Pannello.TestoRiepilogo}). */
    private String TestoRiepilogo() {
        if (Elenco.isEmpty()) {
            return "Nessuna dichiarazione";
        }
        int definitive = 0;
        for (Dichiarazioni.Dichiarazione d : Elenco) {
            if (d.Definitiva) {
                definitive++;
            }
        }
        return Elenco.size() + (Elenco.size() == 1 ? " dichiarazione, " : " dichiarazioni, ")
                + definitive + (definitive == 1 ? " definitiva" : " definitive");
    }

    private void MostraDettaglio() {
        ModelloDettaglio().setRowCount(0);
        for (Object[] r : Principale_Dichiarazioni.RigheDettaglio(Selezionata())) {
            ModelloDettaglio().addRow(r);
        }
        AdattaLarghezzaColonne(Tabella_Dettaglio);
    }

    /** @return la dichiarazione della riga selezionata, {@code null} se la selezione non è di una sola riga */
    private Dichiarazioni.Dichiarazione Selezionata() {
        if (Tabella_Elenco.getSelectedRowCount() != 1) {
            return null;
        }
        int riga = Tabella_Elenco.convertRowIndexToModel(Tabella_Elenco.getSelectedRow());
        return riga >= 0 && riga < Elenco.size() ? Elenco.get(riga) : null;
    }

    private void AggiornaStatoPulsanti() {
        int selezionate = Tabella_Elenco.getSelectedRowCount();
        Dichiarazioni.Dichiarazione d = Selezionata();
        Bottone_ApriPdf.setEnabled(selezionate == 1);
        Bottone_ApriExcel.setEnabled(selezionate == 1);
        Bottone_ApriCartella.setEnabled(selezionate == 1);
        Bottone_Definitiva.setEnabled(selezionate == 1);
        Bottone_Definitiva.setToolTipText(d != null && d.Definitiva
                ? "Toglie il segno di definitiva dalla dichiarazione selezionata"
                : "Segna la dichiarazione presentata per quell'anno: una sola per anno e per quadro");
        Bottone_Nota.setEnabled(selezionate == 1);
        Bottone_Allegati.setEnabled(selezionate == 1);
        Bottone_Confronta.setEnabled(selezionate == 2);
        Bottone_Continuita.setEnabled(d != null && d.Fam == Dichiarazioni.Famiglia.RW);
        Bottone_Esporta.setEnabled(selezionate == 1);
        Bottone_Elimina.setEnabled(selezionate > 0);
    }

    /** La finestra dei dialoghi, risolta a ogni chiamata: montato in un tab, l'antenato all'inizio non c'è. */
    private Window Proprietario() {
        return SwingUtilities.getWindowAncestor(this);
    }

    private DefaultTableModel ModelloElenco() {
        return (DefaultTableModel) Tabella_Elenco.getModel();
    }

    private DefaultTableModel ModelloDettaglio() {
        return (DefaultTableModel) Tabella_Dettaglio.getModel();
    }

    /** Porta ogni colonna alla larghezza del suo contenuto più lungo, con un tetto. */
    private void AdattaLarghezzaColonne(javax.swing.JTable t) {
        DefaultTableModel modello = (DefaultTableModel) t.getModel();
        for (int c = 0; c < t.getColumnCount(); c++) {
            int larghezza = t.getTableHeader().getDefaultRenderer()
                    .getTableCellRendererComponent(t, modello.getColumnName(c), false, false, 0, c)
                    .getPreferredSize().width;
            for (int r = 0; r < t.getRowCount(); r++) {
                larghezza = Math.max(larghezza,
                        t.prepareRenderer(t.getCellRenderer(r, c), r, c).getPreferredSize().width);
            }
            t.getColumnModel().getColumn(c).setPreferredWidth(Math.min(larghezza + 20, 900));
        }
    }

