    private void Bottone_AllegatiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_AllegatiActionPerformed
        Dichiarazioni.Dichiarazione d = Selezionata();
        if (d == null) {
            return;
        }
        JPopupMenu menu = new JPopupMenu();
        JMenuItem aggiungi = new JMenuItem("Aggiungi un allegato...");
        aggiungi.addActionListener(e -> {
            if (Principale_Dichiarazioni.AggiungiAllegato(d, Proprietario())) {
                RicaricaMantenendoSelezione(d);
            }
        });
        menu.add(aggiungi);
        if (!d.Allegati.isEmpty()) {
            menu.addSeparator();
        }
        for (String nome : d.Allegati.keySet()) {
            JMenuItem togli = new JMenuItem("Togli " + nome);
            togli.addActionListener(e -> {
                if (Principale_Dichiarazioni.RimuoviAllegato(d, nome, Proprietario())) {
                    RicaricaMantenendoSelezione(d);
                }
            });
            menu.add(togli);
        }
        menu.show(Bottone_Allegati, 0, Bottone_Allegati.getHeight());
    }//GEN-LAST:event_Bottone_AllegatiActionPerformed

