    /**
     * Dice al pannello cosa far eseguire dopo un ripristino riuscito.
     *
     * <p>Da valorizzare da {@code Principale} : ricaricare i movimenti, invalidare lo stato del motore
     * incrementale e rifare i calcoli richiede metodi che stanno lì e che non sono raggiungibili da qui.
     *
     * @param Azione riceve l'esito del ripristino
     */
    public void ImpostaAzionePostRipristino(Consumer<Backup_Restore.EsitoRipristino> Azione) {
        AzionePostRipristino = Azione;
    }

    /** Rilegge la cartella degli archivi e ricostruisce le due tabelle. */
    public final void Ricarica() {
        Component c = Proprietario() != null ? Proprietario() : this;
        c.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
        try {
            Manifesti = Backup_Restore.Elenco();
            ModelloElenco().setRowCount(0);
            for (Object[] r : Principale_Backup.RigheElenco(Manifesti)) {
                ModelloElenco().addRow(r);
            }
            Label_Riepilogo.setText(TestoRiepilogo());
            AdattaLarghezzaColonne(Tabella_Elenco);
        } finally {
            c.setCursor(Cursor.getDefaultCursor());
        }
        MostraDettaglio();
        AggiornaStatoPulsanti();
    }

    /**
     * @return la riga di riepilogo in fondo al pannello
     *
     * <p>Volutamente <b>corta</b>: sta nella stessa riga dei sei pulsanti, e in un
     * {@code GroupLayout} una {@code JLabel} non si restringe sotto la propria larghezza preferita —
     * un testo lungo spingerebbe l'ultimo pulsante fuori dal pannello. Il resto (la ritenzione eterna,
     * il fatto che si cancelli solo a mano) sta nel tooltip di <i>Elimina</i>, dove serve davvero.
     */
    private String TestoRiepilogo() {
        long byteTotali = 0;
        for (Backup_Restore.Manifest m : Manifesti) {
            byteTotali += m.DimensioneCompressa;
        }
        if (Manifesti.isEmpty()) {
            return "Nessun backup presente";
        }
        return Manifesti.size() + (Manifesti.size() == 1 ? " backup, " : " backup, ")
                + Backup_Restore.DimensioneLeggibile(byteTotali);
    }

    /** Riempie la tabella inferiore con il dettaglio della riga selezionata. */
    private void MostraDettaglio() {
        ModelloDettaglio().setRowCount(0);
        for (Object[] r : Principale_Backup.RigheDettaglio(Selezionato())) {
            ModelloDettaglio().addRow(r);
        }
        AdattaLarghezzaColonne(Tabella_Dettaglio);
    }

    /** @return il manifest della riga selezionata, {@code null} se la selezione non è di una sola riga */
    private Backup_Restore.Manifest Selezionato() {
        if (Tabella_Elenco.getSelectedRowCount() != 1) {
            return null;
        }
        int riga = Tabella_Elenco.convertRowIndexToModel(Tabella_Elenco.getSelectedRow());
        return riga >= 0 && riga < Manifesti.size() ? Manifesti.get(riga) : null;
    }

    /** Seleziona la riga che corrisponde a un archivio, se presente. */
    private void SelezionaArchivio(File Archivio) {
        for (int i = 0; i < Manifesti.size(); i++) {
            if (Archivio.equals(Manifesti.get(i).Archivio)) {
                int vista = Tabella_Elenco.convertRowIndexToView(i);
                if (vista >= 0) {
                    Tabella_Elenco.setRowSelectionInterval(vista, vista);
                }
                return;
            }
        }
    }

    private void AggiornaStatoPulsanti() {
        int selezionate = Tabella_Elenco.getSelectedRowCount();
        //Ripristino ed esportazione lavorano su un archivio solo: non esiste un ripristino "di due backup"
        Bottone_Ripristina.setEnabled(selezionate == 1);
        Bottone_Esporta.setEnabled(selezionate == 1);
        Bottone_Elimina.setEnabled(selezionate > 0);
    }

