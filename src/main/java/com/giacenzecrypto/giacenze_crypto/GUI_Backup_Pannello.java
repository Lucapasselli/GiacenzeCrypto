    private void Bottone_RipristinaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_RipristinaActionPerformed
        Backup_Restore.Manifest m = Selezionato();
        if (m == null || m.Archivio == null) {
            return;
        }
        Backup_Restore.EsitoRipristino esito = Principale_Backup.RipristinaBackup(m.Archivio, Proprietario());
        if (esito == null) {
            return;
        }
        //Il backup di sicurezza creato prima del ripristino è un archivio nuovo: l'elenco va riletto
        //comunque, anche se il ripristino è poi fallito
        Ricarica();
        if (AzionePostRipristino != null) {
            AzionePostRipristino.accept(esito);
        } else {
            //Montato fuori da Principale non c'è nessuno che possa ricaricare: meglio dirlo che lasciare
            //l'applicazione con i dati vecchi in memoria e quelli nuovi su disco
            Messaggi.WarningMessage("Ripristino",
                    "I dati sono stati ripristinati ma l'applicazione non li ha ancora ricaricati.",
                    "Chiudi e riapri Giacenze Crypto per lavorare sui dati ripristinati.", Proprietario());
        }
    }//GEN-LAST:event_Bottone_RipristinaActionPerformed

    private void Bottone_EsportaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_EsportaActionPerformed
        Backup_Restore.Manifest m = Selezionato();
        if (m != null && m.Archivio != null) {
            Principale_Backup.EsportaBackup(m.Archivio, Proprietario());
        }
    }//GEN-LAST:event_Bottone_EsportaActionPerformed

    private void Bottone_ImportaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_ImportaActionPerformed
        File importato = Principale_Backup.ImportaBackup(Proprietario());
        Ricarica();
        //ImportaBackup ritorna un file solo se l'utente ha chiesto di ripristinarlo subito: in quel caso
        //si seleziona la riga e si passa dalla stessa conferma del pulsante, senza scorciatoie
        if (importato != null) {
            SelezionaArchivio(importato);
            Bottone_RipristinaActionPerformed(evt);
        }
    }//GEN-LAST:event_Bottone_ImportaActionPerformed

    private void Bottone_EliminaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_EliminaActionPerformed
        List<File> archivi = new ArrayList<>();
        for (int riga : Tabella_Elenco.getSelectedRows()) {
            Backup_Restore.Manifest m = Manifesti.get(Tabella_Elenco.convertRowIndexToModel(riga));
            if (m.Archivio != null) {
                archivi.add(m.Archivio);
            }
        }
        if (Principale_Backup.EliminaBackup(archivi, Proprietario())) {
            Ricarica();
        }
    }//GEN-LAST:event_Bottone_EliminaActionPerformed

