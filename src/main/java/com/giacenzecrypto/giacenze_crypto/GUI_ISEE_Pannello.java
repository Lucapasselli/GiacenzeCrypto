    /**
     * Calcola i rapporti dell'anno in background, con la finestra di avanzamento (i prezzi di fine anno che mancano
     * si scaricano). Interrotto, non mostra nulla: un risultato a metà prezzi sembrerebbe solo "incompleto".
     *
     * @param chiaveDaSelezionare il rapporto da riselezionare dopo il calcolo, {@code null} = nessuno
     * @param conMedia {@code true} per rifare anche la media giornaliera (era già stata calcolata)
     */
    private void Calcola(int anno, String chiaveDaSelezionare, boolean conMedia) {
        Download progress = new Download();
        progress.setLocationRelativeTo(Proprietario());
        progress.Titolo("ISEE: calcolo dei rapporti del " + anno);
        progress.NascondiBarra();
        Calcoli_ISEE.Risultato[] esito = new Calcoli_ISEE.Risultato[1];
        Thread t = new Thread(() -> {
            try {
                esito[0] = Principale_ISEE.Calcola(anno, progress);
            } catch (RuntimeException ex) {
                LoggerGC.ScriviErrore(ex);
            } finally {
                SwingUtilities.invokeLater(progress::ChiudiFineLavoro);
            }
        }, "ISEE-calcolo");
        t.start();
        progress.setVisible(true);
        if (esito[0] == null) {
            Messaggi.WarningMessage("Calcolo non completato", "Il calcolo è stato interrotto o non è riuscito: "
                    + "la tabella mostra ancora il risultato precedente.", Proprietario());
            return;
        }
        Ris = esito[0];
        if (conMedia) {
            Media(chiaveDaSelezionare);
        } else {
            Riempi(chiaveDaSelezionare);
        }
    }

    /**
     * La media giornaliera dei rapporti 99 sull'ultimo calcolo, in due passi: prima conta (senza rete) le quotazioni
     * che mancano e, se ci vuole più di un minuto, chiede conferma con la stima. Poi le scarica (interrompibile: quello
     * che è arrivato resta in cache) e calcola. Interrotta, la tabella resta com'era.
     */
    private void Media(String chiaveDaSelezionare) {
        Calcoli_ISEE.Risultato ris = Ris;
        Download preparazione = new Download();
        preparazione.setLocationRelativeTo(Proprietario());
        preparazione.Titolo("ISEE: media giornaliera del " + ris.anno);
        preparazione.NascondiBarra();
        Principale_ISEE_Media.Piano[] piano = new Principale_ISEE_Media.Piano[1];
        Thread t = new Thread(() -> {
            try {
                piano[0] = Principale_ISEE_Media.Prepara(ris, preparazione);
            } catch (RuntimeException ex) {
                LoggerGC.ScriviErrore(ex);
            } finally {
                SwingUtilities.invokeLater(preparazione::ChiudiFineLavoro);
            }
        }, "ISEE-media-piano");
        t.start();
        preparazione.setVisible(true);
        if (piano[0] == null || preparazione.FineThread()) {
            Riempi(chiaveDaSelezionare);
            return;
        }
        if (piano[0].secondiStimati() >= 60 && !ConfermaScaricamento(piano[0])) {
            Riempi(chiaveDaSelezionare);
            return;
        }

        Download progress = new Download();
        progress.setLocationRelativeTo(Proprietario());
        progress.Titolo("ISEE: media giornaliera del " + ris.anno);
        boolean[] fatto = new boolean[1];
        Thread s = new Thread(() -> {
            try {
                if (Principale_ISEE_Media.Scarica(piano[0], progress)) {
                    Principale_ISEE_Media.CalcolaMedia(ris, progress);
                    fatto[0] = true;
                }
            } catch (RuntimeException ex) {
                LoggerGC.ScriviErrore(ex);
            } finally {
                SwingUtilities.invokeLater(progress::ChiudiFineLavoro);
            }
        }, "ISEE-media");
        s.start();
        progress.setVisible(true);
        if (!fatto[0]) {
            Messaggi.WarningMessage("Media non calcolata", "Lo scaricamento dei prezzi è stato interrotto o non è riuscito. "
                    + "I prezzi già arrivati restano: ripetendo il calcolo si riparte da lì.", Proprietario());
        }
        Riempi(chiaveDaSelezionare);
    }

    private boolean ConfermaScaricamento(Principale_ISEE_Media.Piano piano) {
        AppDialog.DialogResult res = AppDialog.builder(Proprietario())
                .windowTitle("Media giornaliera")
                .bodyTitle("Scaricare i prezzi giornalieri?")
                .showTitleInBody(true)
                .theme()
                .type(AppDialog.DialogType.INFO)
                .message(Principale_ISEE_Media.DescriviPiano(piano))
                .action(AppDialog.DialogAction.builder("annulla", "Annulla").role(AppDialog.ActionRole.SECONDARY).build())
                .action(AppDialog.DialogAction.builder("scarica", "Scarica e calcola").role(AppDialog.ActionRole.PRIMARY).build())
                .showDialog();
        return res != null && res.isAction("scarica");
    }

    /** Riempie la tabella dei rapporti dall'ultimo calcolo. */
    private void Riempi(String chiaveDaSelezionare) {
        DefaultTableModel m = (DefaultTableModel) Tabella_Rapporti.getModel();
        m.setRowCount(0);
        int daSelezionare = -1;
        for (int i = 0; i < Ris.rapporti.size(); i++) {
            Calcoli_ISEE.Rapporto r = Ris.rapporti.get(i);
            m.addRow(Principale_ISEE.Riga(r));
            if (r.chiave.equals(chiaveDaSelezionare)) {
                daSelezionare = i;
            }
        }
        Label_Riepilogo.setText(Principale_ISEE.Riepilogo(Ris));
        AdattaLarghezzaColonne(Tabella_Rapporti);
        if (daSelezionare >= 0) {
            int vista = Tabella_Rapporti.convertRowIndexToView(daSelezionare);
            Tabella_Rapporti.setRowSelectionInterval(vista, vista);
        }
        MostraDettaglio();
        AggiornaScollegati();
        AggiornaStatoPulsanti();
    }

    /** Modifica i dati del rapporto selezionato e ricalcola: una chiusura cambia giorni, media, valore e avvisi. */
    private void Modifica() {
        Calcoli_ISEE.Rapporto r = Selezionato();
        if (r != null && Principale_ISEE.ModificaDati(r, Proprietario())) {
            Calcola(Ris.anno, r.chiave, Ris.mediaCalcolata);
        }
    }

    private void MostraDettaglio() {
        DefaultTableModel m = (DefaultTableModel) Tabella_Dettaglio.getModel();
        m.setRowCount(0);
        for (Object[] riga : Principale_ISEE.Dettaglio(Selezionato())) {
            m.addRow(riga);
        }
        AdattaLarghezzaColonne(Tabella_Dettaglio);
    }

    private void AggiornaScollegati() {
        int n = Principale_ISEE.DatiScollegati().size();
        Bottone_Scollegati.setText(n == 0 ? "Dati senza rapporto" : "Dati senza rapporto (" + n + ")");
        Bottone_Scollegati.setEnabled(n > 0);
    }

    private void AggiornaStatoPulsanti() {
        Bottone_Modifica.setEnabled(Selezionato() != null);
        Bottone_Media.setEnabled(Ris != null);
        int mancanti = Ris == null || !Ris.mediaCalcolata ? 0 : Ris.prezziMancanti.size();
        Bottone_PrezziMancanti.setEnabled(mancanti > 0);
        Bottone_PrezziMancanti.setText(mancanti == 0 ? "Prezzi mancanti..." : "Prezzi mancanti (" + mancanti + ")...");
    }

    /** @return il rapporto della riga selezionata, {@code null} se non ce n'è uno */
    private Calcoli_ISEE.Rapporto Selezionato() {
        if (Ris == null || Tabella_Rapporti.getSelectedRowCount() != 1) {
            return null;
        }
        int riga = Tabella_Rapporti.convertRowIndexToModel(Tabella_Rapporti.getSelectedRow());
        return riga >= 0 && riga < Ris.rapporti.size() ? Ris.rapporti.get(riga) : null;
    }

    /** La finestra dei dialoghi, risolta a ogni chiamata: montato in un tab, l'antenato all'inizio non c'è. */
    private Window Proprietario() {
        return SwingUtilities.getWindowAncestor(this);
    }

    /** Porta ogni colonna alla larghezza del suo contenuto più lungo, con un tetto. */
    private void AdattaLarghezzaColonne(javax.swing.JTable t) {
        DefaultTableModel modello = (DefaultTableModel) t.getModel();
        for (int c = 0; c < t.getColumnCount(); c++) {
            int larghezza = t.getTableHeader().getDefaultRenderer()
                    .getTableCellRendererComponent(t, modello.getColumnName(c), false, false, 0, c)
                    .getPreferredSize().width;
            for (int r = 0; r < t.getRowCount(); r++) {
                larghezza = Math.max(larghezza,
                        t.prepareRenderer(t.getCellRenderer(r, c), r, c).getPreferredSize().width);
            }
            t.getColumnModel().getColumn(c).setPreferredWidth(Math.min(larghezza + 20, 900));
        }
    }

