    private void Bottone_OkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_OkActionPerformed
        Calcoli_ISEE.DatiUtente d = new Calcoli_ISEE.DatiUtente();
        d.identificativo = Campo_Ident.getText().trim();
        d.operatore = Campo_Operatore.getText().trim().toUpperCase();
        String apertura = RwDialoghi.leggiData(Data_Apertura);
        String chiusura = RwDialoghi.leggiData(Data_Chiusura);
        d.apertura = apertura.isEmpty() ? null : LocalDate.parse(apertura);
        d.chiusura = chiusura.isEmpty() ? null : LocalDate.parse(chiusura);
        if (d.apertura != null && d.chiusura != null && d.chiusura.isBefore(d.apertura)) {
            Messaggi.WarningMessage("Date non valide", "La data di chiusura è precedente alla data di apertura.", this);
            return;
        }
        risultato = d;
        confermato = true;
        dispose();
    }//GEN-LAST:event_Bottone_OkActionPerformed

