    private void Bottone_PrezzoTrattiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_PrezzoTrattiActionPerformed
        List<Principale_ISEE_Media.Tratto> sel = trattiSelezionati();
        if (sel.isEmpty()) {
            return;
        }
        List<Calcoli_ISEE.PrezzoMancante> giorni = giorniDi(sel);
        BigDecimal prezzo = chiediPrezzo(giorni.size() + " giorni di " + sel.size() + (sel.size() == 1 ? " tratto" : " tratti"));
        if (prezzo != null) {
            scrivi(sel, giorni, prezzo);
        }
    }//GEN-LAST:event_Bottone_PrezzoTrattiActionPerformed

    private void Bottone_PrezzoGiorniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bottone_PrezzoGiorniActionPerformed
        Principale_ISEE_Media.Tratto t = trattoUnico();
        if (t == null || Tabella_Giorni.getSelectedRowCount() == 0) {
            return;
        }
        List<Calcoli_ISEE.PrezzoMancante> giorni = new ArrayList<>();
        for (int v : Tabella_Giorni.getSelectedRows()) {
            giorni.add(t.giorni.get(Tabella_Giorni.convertRowIndexToModel(v)));
        }
        BigDecimal prezzo = chiediPrezzo(giorni.size() == 1 ? "il " + giorni.get(0).giorno.format(GG_MM_AAAA)
                : giorni.size() + " giorni");
        if (prezzo != null) {
            scrivi(List.of(), giorni, prezzo);
        }
    }//GEN-LAST:event_Bottone_PrezzoGiorniActionPerformed

