    /** Il prezzo unitario in euro chiesto all'utente, {@code null} se annulla. Ripete la domanda se il testo non è un prezzo. */
    private BigDecimal chiediPrezzo(String cosa) {
        Moneta m = trattiSelezionati().isEmpty() ? null : trattiSelezionati().get(0).moneta;
        String testo = "";
        while (true) {
            testo = AppDialog.showTextInputDialog(this, "Prezzo personalizzato", "Prezzo unitario in euro",
                    "Prezzo di fine giornata per " + cosa + (m == null ? "" : " di " + m.Moneta) + ".",
                    "Prezzo unitario (EUR)", testo);
            if (testo == null) {
                return null;
            }
            BigDecimal p = Principale_ISEE_Media.LeggiPrezzo(testo);
            if (p != null) {
                return p;
            }
            Messaggi.WarningMessage("Prezzo non valido", "Scrivi un numero non negativo, per esempio 0,05.", this);
        }
    }

    /** Scrive i prezzi in background con la finestra di avanzamento (i giorni possono essere migliaia). */
    private void scrivi(List<Principale_ISEE_Media.Tratto> trattiInteri, List<Calcoli_ISEE.PrezzoMancante> giorni, BigDecimal prezzo) {
        Download progress = new Download();
        progress.setLocationRelativeTo(this);
        progress.Titolo("ISEE: scrittura dei prezzi");
        progress.SetLabel("Scrittura di " + giorni.size() + " prezzi personalizzati...");
        boolean[] ok = new boolean[1];
        Thread t = new Thread(() -> {
            try {
                ok[0] = Principale_ISEE_Media.ScriviPrezzi(giorni, prezzo, progress);
            } finally {
                SwingUtilities.invokeLater(progress::ChiudiFineLavoro);
            }
        }, "ISEE-prezzi");
        t.start();
        progress.setVisible(true);
        if (!ok[0]) {
            Messaggi.WarningMessage("Prezzi non salvati", "La scrittura nel database non è riuscita, nessun prezzo è stato salvato: "
                    + "i dettagli sono nel log.", this);
            return;
        }
        modificato = true;
        sistemati.addAll(trattiInteri);
        DefaultTableModel m = (DefaultTableModel) Tabella_Tratti.getModel();
        for (int i = 0; i < tratti.size(); i++) {
            m.setValueAt(rigaTratto(tratti.get(i))[0], i, 0);
        }
        Label_Giorni.setText("Giorni del tratto selezionato (prezzi scritti: " + giorni.size() + ", la media si ricalcola alla chiusura)");
    }

    private Object[] rigaTratto(Principale_ISEE_Media.Tratto t) {
        Moneta m = t.moneta;
        BigDecimal min = t.qtaMin();
        BigDecimal max = t.qtaMax();
        String qta = min.compareTo(max) == 0 ? qta(min) : qta(min) + " - " + qta(max);
        return new Object[] {
            m.Moneta + (sistemati.contains(t) ? " (prezzo scritto)" : ""),
            m.Rete == null ? "" : m.Rete,
            m.MonetaAddress == null ? "" : m.MonetaAddress,
            t.dal().format(GG_MM_AAAA),
            t.al().format(GG_MM_AAAA),
            String.valueOf(t.giorni.size()),
            qta,
            String.join(", ", alias(t.gruppi()))
        };
    }

    private void mostraGiorni() {
        DefaultTableModel m = (DefaultTableModel) Tabella_Giorni.getModel();
        m.setRowCount(0);
        Principale_ISEE_Media.Tratto t = trattoUnico();
        if (t == null) {
            return;
        }
        for (Calcoli_ISEE.PrezzoMancante g : t.giorni) {
            m.addRow(new Object[] {g.giorno.format(GG_MM_AAAA), qta(g.qta), String.join(", ", alias(g.gruppi))});
        }
    }

    private void aggiornaPulsanti() {
        boolean tratto = Tabella_Tratti.getSelectedRowCount() > 0;
        Bottone_Zero.setEnabled(tratto);
        Bottone_PrezzoTratti.setEnabled(tratto);
        Bottone_PrezzoGiorni.setEnabled(trattoUnico() != null && Tabella_Giorni.getSelectedRowCount() > 0);
    }

    private List<Principale_ISEE_Media.Tratto> trattiSelezionati() {
        List<Principale_ISEE_Media.Tratto> out = new ArrayList<>();
        for (int v : Tabella_Tratti.getSelectedRows()) {
            out.add(tratti.get(Tabella_Tratti.convertRowIndexToModel(v)));
        }
        return out;
    }

    /** Il tratto selezionato quando ce n'è uno solo (i giorni si mostrano solo allora). */
    private Principale_ISEE_Media.Tratto trattoUnico() {
        List<Principale_ISEE_Media.Tratto> sel = trattiSelezionati();
        return sel.size() == 1 ? sel.get(0) : null;
    }

    private static List<Calcoli_ISEE.PrezzoMancante> giorniDi(List<Principale_ISEE_Media.Tratto> sel) {
        List<Calcoli_ISEE.PrezzoMancante> out = new ArrayList<>();
        for (Principale_ISEE_Media.Tratto t : sel) {
            out.addAll(t.giorni);
        }
        return out;
    }

    private static List<String> alias(java.util.Collection<String> gruppi) {
        List<String> out = new ArrayList<>();
        for (String g : gruppi) {
            out.add(Calcoli_ISEE.aliasDi(g));
        }
        return out;
    }

    private static String qta(BigDecimal q) {
        return q.stripTrailingZeros().toPlainString();
    }

